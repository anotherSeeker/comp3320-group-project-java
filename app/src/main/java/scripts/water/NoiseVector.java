package scripts.water;

public class NoiseVector
{
    public double x;
    public double y;

    public NoiseVector(double x, double y)
    {
        this.x = x;
        this.y = y;
    }

    public double getX()
    {
        return x;
    }

    public double getY()
    {
        return y;
    }
}
